/**
 * Colours Android's own scroll bar to match the app.
 *
 * The bar stays the platform's: it still shows while a list or page is
 * scrolling and fades once it stops. Only its thumb is replaced, because the
 * stock one is a light translucent grey that all but disappears on the cream
 * background. The thumb takes the theme's muted text colour — the same ink
 * captions use — slightly translucent, so it reads without competing with
 * the content it sits over.
 *
 * Night resources follow the phone's system setting, not the in-app theme
 * choice, which is JS-only. Both colours are mid-tones for that reason: the
 * light one still shows on the dark background if the two ever disagree.
 *
 * Native files are generated by `expo prebuild`, so this lives here rather
 * than in `android/`.
 */

const fs = require('fs');
const path = require('path');
const {
  AndroidConfig,
  withAndroidColors,
  withAndroidColorsNight,
  withAndroidStyles,
  withDangerousMod,
} = require('expo/config-plugins');

const COLOR_NAME = 'scrollbarThumb';
const DRAWABLE_NAME = 'scrollbar_thumb';

// ARGB: `B3` is 70% opacity over `mutedForeground` from `themes.ts`.
const LIGHT = '#B3686054';
const DARK = '#B3C1B4A7';

const THUMB_XML = `<?xml version="1.0" encoding="utf-8"?>
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
  <solid android:color="@color/${COLOR_NAME}" />
  <corners android:radius="2dp" />
  <size android:width="4dp" />
</shape>
`;

function setColor(config, value) {
  config.modResults = AndroidConfig.Colors.assignColorValue(config.modResults, {
    name: COLOR_NAME,
    value,
  });
  return config;
}

module.exports = function withScrollbarThumb(config) {
  config = withAndroidColors(config, (next) => setColor(next, LIGHT));
  config = withAndroidColorsNight(config, (next) => setColor(next, DARK));

  config = withDangerousMod(config, [
    'android',
    (next) => {
      const drawables = path.join(
        next.modRequest.platformProjectRoot,
        'app/src/main/res/drawable',
      );
      fs.mkdirSync(drawables, { recursive: true });
      fs.writeFileSync(path.join(drawables, `${DRAWABLE_NAME}.xml`), THUMB_XML);
      return next;
    },
  ]);

  return withAndroidStyles(config, (next) => {
    next.modResults = AndroidConfig.Styles.assignStylesValue(next.modResults, {
      add: true,
      parent: AndroidConfig.Styles.getAppThemeGroup(),
      name: 'android:scrollbarThumbVertical',
      value: `@drawable/${DRAWABLE_NAME}`,
    });
    return next;
  });
};

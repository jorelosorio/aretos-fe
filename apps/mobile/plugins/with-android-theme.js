/**
 * Tunes two of Android's own theme colours to the app, in both schemes.
 *
 * Both stay the platform's behaviour; only their colour changes.
 *
 * - **Scroll bar.** The bar still shows while a list or page scrolls and
 *   fades once it stops. The stock thumb is a light translucent grey that all
 *   but disappears on the cream background, so it takes the theme's muted
 *   text colour instead, the same ink captions use, slightly translucent.
 * - **Press highlight** (`colorControlHighlight`). The ripple Android draws
 *   behind a pressed native control, such as the header's back button.
 *   Stock, it is 12% black in light and 20% white in dark: on the cream page
 *   the first barely shows while the second is a bright disc, so the same
 *   press looks different in each scheme. Here it is one strength in both,
 *   16% of the theme's own text colour.
 *
 * Which set Android uses follows the in-app theme: the root layout passes
 * the person's choice to `Appearance.setColorScheme`, so the native night
 * mode matches the scheme the app is drawn in rather than the phone's.
 *
 * Native files are generated by `expo prebuild`, so this lives here rather
 * than in `android/`.
 */

const fs = require('fs');
const path = require('path');
const {
  AndroidConfig,
  withAndroidColors,
  withAndroidColorsNight,
  withAndroidStyles,
  withDangerousMod,
} = require('expo/config-plugins');

// ARGB. `B3` is 70% opacity and `29` is 16%, over colours from `themes.ts`:
// `mutedForeground` for the thumb, the text colour for the highlight.
const COLORS = {
  scrollbarThumb: { light: '#B3686054', dark: '#B3C1B4A7' },
  controlHighlight: { light: '#292A211B', dark: '#29F5EADE' },
};

const THUMB_DRAWABLE = 'scrollbar_thumb';

const THUMB_XML = `<?xml version="1.0" encoding="utf-8"?>
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
  <solid android:color="@color/scrollbarThumb" />
  <corners android:radius="2dp" />
  <size android:width="4dp" />
</shape>
`;

// `colorControlHighlight` is read under both names: AppCompat's own
// attribute by its widgets, the platform one by native ripples.
const THEME_ITEMS = {
  'android:scrollbarThumbVertical': `@drawable/${THUMB_DRAWABLE}`,
  colorControlHighlight: '@color/controlHighlight',
  'android:colorControlHighlight': '@color/controlHighlight',
};

function setColors(config, scheme) {
  for (const [name, values] of Object.entries(COLORS)) {
    config.modResults = AndroidConfig.Colors.assignColorValue(
      config.modResults,
      { name, value: values[scheme] },
    );
  }
  return config;
}

module.exports = function withAndroidTheme(config) {
  config = withAndroidColors(config, (next) => setColors(next, 'light'));
  config = withAndroidColorsNight(config, (next) => setColors(next, 'dark'));

  config = withDangerousMod(config, [
    'android',
    (next) => {
      const drawables = path.join(
        next.modRequest.platformProjectRoot,
        'app/src/main/res/drawable',
      );
      fs.mkdirSync(drawables, { recursive: true });
      fs.writeFileSync(
        path.join(drawables, `${THUMB_DRAWABLE}.xml`),
        THUMB_XML,
      );
      return next;
    },
  ]);

  return withAndroidStyles(config, (next) => {
    for (const [name, value] of Object.entries(THEME_ITEMS)) {
      next.modResults = AndroidConfig.Styles.assignStylesValue(
        next.modResults,
        {
          add: true,
          parent: AndroidConfig.Styles.getAppThemeGroup(),
          name,
          value,
        },
      );
    }
    return next;
  });
};
